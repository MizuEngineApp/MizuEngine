        {
            ("system", ""), ("ru", "Русский"), ("en", "English"), ("zh", "简体中文"),
            ("ja", "日本語"), ("ko", "한국어"), ("sv", "Svenska"), ("pt", "Português")
        };

        public static event Action Changed;
        static Dictionary<string, string> _current;

        /// <summary>Код текущего языка: ru, en, zh…</summary>
        public static string Code { get; private set; } = "en";

        public static void Apply(string setting)
        {
            string code = setting != null && All.ContainsKey(setting) ? setting : FromSystem();
            _current = All[code];
            Code = code;
            var res = Application.Current.Resources;
            foreach (var kv in All["en"])
                res[kv.Key] = _current.TryGetValue(kv.Key, out var v) ? v : kv.Value;
            Changed?.Invoke();
        }

        public static string T(string key) =>
            _current != null && _current.TryGetValue(key, out var v) ? v :
            All["en"].TryGetValue(key, out var e) ? e : key;

        static string FromSystem()
        {
            string c = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;  // для любого китайского вернёт "zh"
            return All.ContainsKey(c) ? c : "en";
        }

        static Dictionary<string, string> Parse(string text)
        {
            var d = new Dictionary<string, string>();
            foreach (var line in text.Split('\n'))
            {
                int i = line.IndexOf('=');
                if (i > 0) d[line.Substring(0, i).Trim()] = line.Substring(i + 1).Trim();
            }
            return d;
        }

